/// Simple hand-rolled localization for English, Urdu and Pashto.
///
/// Urdu and Pashto are RTL; the app wraps itself in the right [Directionality]
/// based on [S.isRtl].
class S {
  final String lang;
  const S(this.lang);

  static const List<String> supported = ['en', 'ur', 'ps'];

  static bool isRtl(String lang) => lang == 'ur' || lang == 'ps';

  String t(String key) {
    final map = _all[lang];
    final v = map?[key] ?? _all['en']![key];
    return v is String ? v : key;
  }

  /// "Sun, Oct 11" style date line, localized.
  String dateLine(DateTime d) {
    final wd = d.weekday; // 1 = Monday
    if (lang == 'ur') {
      return '${_urDays[wd - 1]}، ${d.day} ${_urMonths[d.month - 1]}';
    }
    if (lang == 'ps') {
      return '${_psDays[wd - 1]}، ${d.day} ${_psMonths[d.month - 1]}';
    }
    return '${_enDaysShort[wd - 1]}, ${_enMonthsShort[d.month - 1]} ${d.day}';
  }

  List<String> get dayShort {
    if (lang == 'ur') return _urDaysShort;
    if (lang == 'ps') return _psDaysShort;
    return _enDaysShort;
  }
}

